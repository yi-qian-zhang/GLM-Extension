"""Make the submission bibliography from the annotated one.

    python strip_notes.py              # writes refs_submit.bib, reports what is still unverified

WHY. `refs.bib` carries a `note` on most entries saying when the citation was checked and against
what, which is the audit trail for a paper whose first draft cited a title and a first author that
did not exist. `plainnat` prints `note`, so the compiled PDF currently shows lines like ``checked
10 Oct 2026 against the PDF'' and ``VERIFY volume/pages'' inside the references. That is right for
us and wrong for a reviewer, and it costs about half a page.

So the annotated file stays the master and this writes the stripped copy that `main.tex` cites.
Nothing is edited in place and nothing is reworded: fields other than `note` are copied through
byte for byte, so the submitted bibliography cannot drift from the audited one.

It also prints the entries whose notes still say VERIFY. Stripping them makes them invisible, and
the point of the exercise is not to hide an unfinished check from ourselves.
"""
from __future__ import annotations

import datetime
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "refs.bib"
DST = HERE / "refs_submit.bib"

HEADER = """% Generated by strip_notes.py from refs.bib on {date} -- DO NOT EDIT.
% The master bibliography is refs.bib, which keeps an audit note on each entry saying when and
% against what it was checked. This copy is that file with the `note` fields removed, because
% plainnat prints them. Edit refs.bib and regenerate; {n} entries.
"""


def split_entries(text: str):
    """[(raw entry text, citekey)] for every @type{...} in the file, braces balanced."""
    out = []
    for m in re.finditer(r"@\w+\s*\{", text):
        i = m.end() - 1                       # at the opening brace
        depth, j = 0, i
        while j < len(text):
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        raw = text[m.start():j + 1]
        key = raw[raw.index("{") + 1:].split(",", 1)[0].strip()
        out.append((raw, key))
    return out


def split_fields(body: str):
    """Split an entry body at top-level commas: [citekey, field, field, ...], raw text kept."""
    parts, depth, start = [], 0, 0
    for i, ch in enumerate(body):
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
        elif ch == "," and depth == 0:
            parts.append(body[start:i])
            start = i + 1
    parts.append(body[start:])
    return parts


def strip(raw: str) -> str:
    head = raw[:raw.index("{") + 1]
    body = raw[raw.index("{") + 1:raw.rindex("}")]
    parts = split_fields(body)
    kept = [parts[0]]                          # the citekey
    for p in parts[1:]:
        name = p.strip().split("=", 1)[0].strip().lower() if "=" in p else ""
        if name == "note":
            continue
        if p.strip():                          # drop the empty tail after a trailing comma
            kept.append(p)
    return head + ",".join(kept).rstrip() + "\n}"


def main() -> int:
    if not SRC.exists():
        print(f"no {SRC}", file=sys.stderr)
        return 1
    text = SRC.read_text(encoding="utf-8")
    ents = split_entries(text)
    stripped = [strip(raw) for raw, _ in ents]

    DST.write_text(
        HEADER.format(date=datetime.date.today().isoformat(), n=len(ents)) + "\n"
        + "\n\n".join(stripped) + "\n", encoding="utf-8", newline="\n")

    dropped = sum(1 for raw, _ in ents if re.search(r"(^|,)\s*note\s*=", raw, re.M))
    print(f"{len(ents)} entries -> {DST.name}, {dropped} notes removed")

    pending = [(k, re.search(r"VERIFY[^}]*", raw, re.S).group(0).split(".")[0])
               for raw, k in ents if "VERIFY" in raw]
    if pending:
        print(f"\nstill unverified in refs.bib ({len(pending)}), invisible once stripped:")
        for k, what in pending:
            print(f"  {k:28s} {' '.join(what.split())[:88]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
