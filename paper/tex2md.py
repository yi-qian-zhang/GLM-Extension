# -*- coding: utf-8 -*-
"""Render the paper's LaTeX sources as one readable Markdown file.

There is no LaTeX on either machine, so this exists to make the draft reviewable without
one. It is a reading view, not a typesetter: it keeps section and paragraph structure,
tables, emphasis and citation keys, and drops everything that only matters for layout.
Generated from the .tex files each time, so it cannot drift from them.
"""
from __future__ import annotations

import re
from pathlib import Path

PAPER = Path(r"E:\OneDrive - Case Western Reserve University\PhD\Research\GLM Collaboration Extensions\GLM-Extension\paper")
OUT = Path(r"E:\OneDrive - Case Western Reserve University\PhD\Research\GLM Collaboration Extensions\GLM-Extension\paper\DRAFT_READABLE.md")

ORDER = ["p00_abstract", "p01_intro", "p02_related", "p03_setup", "p04_leak",
         "p05_identify", "p06_slots", "p07_practice", "p08_discussion"]

MACROS = {
    r"\bits": "bits/nt",
    r"\nt": " nt",
    r"\excess": "Δ",
    r"\CODEURL": "[public repository URL — TODO]",
}


def tabular_to_md(body: str) -> str:
    """One LaTeX tabular body to a Markdown table. Multicolumn headers are flattened."""
    rows = []
    for raw in body.split(r"\\"):
        line = raw.strip()
        if not line or line.startswith("%"):
            continue
        for rule in (r"\toprule", r"\midrule", r"\bottomrule"):
            line = line.replace(rule, "")
        line = re.sub(r"\\cmidrule\(lr\)\{[^}]*\}", "", line)
        line = re.sub(r"\\multicolumn\{\d+\}\{[^}]*\}\{([^}]*)\}", r"\1", line)
        line = line.strip()
        if not line:
            continue
        cells = [c.strip() for c in line.split("&")]
        rows.append(cells)
    if not rows:
        return ""
    width = max(len(r) for r in rows)
    rows = [r + [""] * (width - len(r)) for r in rows]
    out = ["| " + " | ".join(rows[0]) + " |",
           "|" + "|".join([" --- "] * width) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows[1:]]
    return "\n".join(out)


def convert(text: str) -> str:
    # tables first, before inline rules touch their contents
    def table_repl(m):
        env = m.group(0)
        cap = re.search(r"\\caption\{(.*?)\}\s*\n", env, re.S)
        lab = re.search(r"\\label\{([^}]+)\}", env)
        tab = re.search(r"\\begin\{tabular\}\{[^}]*\}(.*?)\\end\{tabular\}", env, re.S)
        parts = []
        if lab:
            parts.append(f"**Table ({lab.group(1)})**")
        if cap:
            parts.append("*" + inline(cap.group(1).strip()) + "*")
        if tab:
            parts.append(inline(tabular_to_md(tab.group(1))))
        return "\n\n".join(parts) + "\n"

    text = re.sub(r"\\begin\{table\}.*?\\end\{table\}", table_repl, text, flags=re.S)
    text = re.sub(r"^\s*%.*$", "", text, flags=re.M)              # comment lines
    text = re.sub(r"\\section\{([^}]*)\}", r"\n## \1\n", text)
    text = re.sub(r"\\paragraph\{([^}]*)\}", r"\n**\1**\n", text)
    text = re.sub(r"\\begin\{enumerate\}[^\n]*", "", text)
    text = re.sub(r"\\end\{enumerate\}", "", text)
    text = re.sub(r"\\itemsep[^\n ]*", "", text)
    text = text.replace(r"\item", "\n1.")
    return inline(text)


def inline(t: str) -> str:
    t = re.sub(r"\\citep\{([^}]+)\}", lambda m: "[" + m.group(1).replace(",", ", ") + "]", t)
    t = re.sub(r"\\citet\{([^}]+)\}", lambda m: "[" + m.group(1).replace(",", ", ") + "]", t)
    t = re.sub(r"\\textbf\{([^}]*)\}", r"**\1**", t)
    t = re.sub(r"\\emph\{([^}]*)\}", r"*\1*", t)
    t = re.sub(r"\\texttt\{([^}]*)\}", r"`\1`", t)
    t = re.sub(r"\\kmer\{([^}]*)\}", r"\1-mer", t)
    t = re.sub(r"\\ref\{([^}]+)\}", lambda m: "§" + m.group(1).split(":")[1], t)
    t = re.sub(r"\\label\{[^}]+\}", "", t)
    for k, v in MACROS.items():
        t = t.replace(k + "{}", v).replace(k, v)
    t = t.replace(r"\%", "%").replace(r"\&", "&").replace(r"\,", " ")
    t = t.replace(r"\emph", "").replace("~", " ")
    t = re.sub(r"\$([^$]*)\$", r"\1", t)
    t = t.replace("``", '"').replace("''", '"').replace("---", "—").replace("--", "–")
    t = re.sub(r"\\[a-zA-Z]+", "", t)                              # any macro left over
    t = t.replace("{", "").replace("}", "")
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t


title = "Released Genomic Language Models Identify the People They Were Fine-Tuned On"
sub = "Reproduction Is the Wrong Alarm, and Tokenisation Explains Why"
doc = [f"# {title}\n\n### {sub}\n",
       "Yiqian Zhang, [co-authors TBD], Erman Ayday — Case Western Reserve University\n",
       "> Reading view generated from `paper/sections/p0*.tex`. Figures are referenced but not yet\n"
       "> drawn, so their numbers appear as section marks. Regenerate with `tex2md.py` after editing\n"
       "> the LaTeX; do not edit this file.\n"]

for name in ORDER:
    f = PAPER / "sections" / f"{name}.tex"
    if not f.exists():
        continue
    body = convert(f.read_text(encoding="utf-8")).strip()
    if name == "p00_abstract":
        doc.append("## Abstract\n\n" + body + "\n")
    else:
        doc.append(body + "\n")

OUT.write_text("\n".join(doc), encoding="utf-8")
words = len(re.findall(r"\b\w+\b", "\n".join(doc)))
print(f"wrote {OUT}  ({words} words, {len(OUT.read_text(encoding='utf-8'))} chars)")
